export function generateMockSeatsForEvent(eventId: string): SeatMapItem[] {
  const rows = ["A", "B", "C", "D", "E", "F", "G", "H"];
  const cols = 12;
  const seats: SeatMapItem[] = [];

  rows.forEach((rowLabel, rIdx) => {
    for (let c = 1; c <= cols; c++) {
      let catId = "cat-std";
      let catName = "Standard";
      let catColor = "#3B82F6";
      let price = 65;

      if (rIdx < 2) {
        catId = "cat-vip";
        catName = "VIP Lounge";
        catColor = "#A855F7";
        price = 220;
      } else if (rIdx < 5) {
        catId = "cat-prem";
        catName = "Premium";
        catColor = "#6366F1";
        price = 140;
      }

      // Determine mock status pattern
      let status: "AVAILABLE" | "HELD" | "BOOKED" = "AVAILABLE";
      let isMyHold = false;

      const randomVal = (rIdx * cols + c) % 7;
      if (randomVal === 0 || randomVal === 3) {
        status = "BOOKED";
      } else if (randomVal === 5 && rIdx === 1 && c === 4) {
        status = "HELD";
      }

      seats.push({
        seat_id: `seat-${eventId}-${rowLabel}${c}`,
        venue_id: "ven-001",
        seat_category_id: catId,
        category_name: catName,
        category_color: catColor,
        row_label: rowLabel,
        seat_number: `${c}`,
        grid_row: rIdx + 1,
        grid_col: c,
        price,
        currency: "USD",
        status,
        is_my_hold: isMyHold,
      });
    }
  });

  return seats;
}

